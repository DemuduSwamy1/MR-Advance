"""Generates the app icon for every platform from one shape spec.

Coordinates use Android's 108x108 adaptive-icon canvas (72x72 visible,
66x66 safe zone, centred on 54,54).
Usage (needs Pillow): python3 tool/make_app_icon.py .
"""
import math
import os
import sys

from PIL import Image, ImageDraw, ImageFilter

ROOT = sys.argv[1]
RES = os.path.join(ROOT, "android/app/src/main/res")

BG = "#246B5E"
DOC = "#FFFFFF"
FOLD = "#B9DED5"
LINE = "#246B5E"
BADGE = "#F4A340"
ARROW = "#FFFFFF"
DX, DY = -2.5, -1.0  # centres the glyph group on the canvas

BADGE_C, BADGE_R, NOTCH_R = (67.0, 68.0), 12.0, 14.5


def arc(cx, cy, r, a0, a1, n=24):
    return [
        (cx + r * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
         cy + r * math.sin(math.radians(a0 + (a1 - a0) * i / n)))
        for i in range(n + 1)
    ]


# Report sheet: rounded corners, cut top-right corner (fold) and a circular
# notch around the badge so the badge reads cleanly at small sizes.
notch_y = BADGE_C[1] - math.sqrt(NOTCH_R**2 - (BADGE_C[0] - 64) ** 2)
notch_x = BADGE_C[0] - math.sqrt(NOTCH_R**2 - (73 - BADGE_C[1]) ** 2)
a_start = math.degrees(math.atan2(notch_y - BADGE_C[1], 64 - BADGE_C[0])) % 360
a_end = math.degrees(math.atan2(73 - BADGE_C[1], notch_x - BADGE_C[0])) % 360
DOC_POINTS = (
    [(37, 29), (55, 29), (64, 38), (64, notch_y)]
    + arc(*BADGE_C, NOTCH_R, a_start, a_end)
    + [(37, 73)]
    + arc(37, 70, 3, 90, 180, 8)
    + arc(37, 32, 3, 180, 270, 8)
)
DOC_PATH = (
    f"M37,29 H55 L64,38 V{notch_y:.3f} "
    f"A{NOTCH_R},{NOTCH_R} 0 0,0 {notch_x:.3f},73 "
    "H37 A3,3 0 0,1 34,70 V32 A3,3 0 0,1 37,29 Z"
)
FOLD_POINTS = [(55, 29), (55, 38), (64, 38)]
FOLD_PATH = "M55,29 V38 H64 Z"

# Fixed-width report lines: (y, x_start, x_end), drawn as pills.
LINES = [(40, 39, 51), (47, 39, 59), (54, 39, 59), (61, 39, 51)]
LINE_H = 1.3

ARROW_POINTS = [
    (61, 66.6), (67, 66.6), (67, 63), (73.5, 68),
    (67, 73), (67, 69.4), (61, 69.4),
]
ARROW_PATH = "M" + " L".join(f"{x},{y}" for x, y in ARROW_POINTS) + " Z"


def pill_path(y, x1, x2, h=LINE_H):
    return (
        f"M{x1},{y - h} H{x2} A{h},{h} 0 0,1 {x2},{y + h} "
        f"H{x1} A{h},{h} 0 0,1 {x1},{y - h} Z"
    )


def circle_path(cx, cy, r):
    return (
        f"M{cx - r},{cy} A{r},{r} 0 1,1 {cx + r},{cy} "
        f"A{r},{r} 0 1,1 {cx - r},{cy} Z"
    )


# ---------------------------------------------------------------- Android XML
def vector(paths, tint_group=True):
    body = "\n".join(
        f'        <path android:fillColor="{c}"'
        + (' android:fillType="evenOdd"' if even else "")
        + f'\n            android:pathData="{d}" />'
        for c, d, even in paths
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_app_icon.py; edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group android:translateX="{DX}" android:translateY="{DY}">
{body}
    </group>
</vector>
"""


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


foreground = [(DOC, DOC_PATH, False), (FOLD, FOLD_PATH, False)]
foreground += [(LINE, pill_path(*l), False) for l in LINES]
foreground += [(BADGE, circle_path(*BADGE_C, BADGE_R), False),
               (ARROW, ARROW_PATH, False)]
write(f"{RES}/drawable/ic_launcher_foreground.xml", vector(foreground))

# Themed (monochrome) icon: one colour, details cut out as holes.
mono = [
    ("#FFFFFF", DOC_PATH + " " + " ".join(pill_path(*l) for l in LINES), True),
    ("#FFFFFF", circle_path(*BADGE_C, BADGE_R) + " " + ARROW_PATH, True),
]
write(f"{RES}/drawable/ic_launcher_monochrome.xml", vector(mono))

write(f"{RES}/mipmap-anydpi-v26/ic_launcher.xml", """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
""")

# ----------------------------------------------------------------- PNG render
SS = 4  # supersampling factor


def render(px):
    """Renders the visible 72x72 viewport (18..90) at px x px, full bleed."""
    size = px * SS
    k = size / 72

    def m(pts):
        return [((x + DX - 18) * k, (y + DY - 18) * k) for x, y in pts]

    img = Image.new("RGBA", (size, size), BG)
    d = ImageDraw.Draw(img)
    d.polygon(m(DOC_POINTS), fill=DOC)
    d.polygon(m(FOLD_POINTS), fill=FOLD)
    for y, x1, x2 in LINES:
        (ax, ay), (bx, by) = m([(x1 - LINE_H, y - LINE_H), (x2 + LINE_H, y + LINE_H)])
        d.rounded_rectangle([ax, ay, bx, by], radius=LINE_H * k, fill=LINE)
    (cx, cy), = m([BADGE_C])
    r = BADGE_R * k
    d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=BADGE)
    d.polygon(m(ARROW_POINTS), fill=ARROW)
    return img.resize((px, px), Image.LANCZOS)


def rounded(img, radius_ratio):
    size = img.size[0] * SS
    mask = Image.new("L", (size, size), 0)
    ImageDraw.Draw(mask).rounded_rectangle(
        [0, 0, size - 1, size - 1], radius=size * radius_ratio, fill=255)
    out = img.copy()
    out.putalpha(mask.resize(img.size, Image.LANCZOS))
    return out


# Legacy launcher icons (Android 7.x and older ignore the adaptive XML).
for folder, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96,
                   "xxhdpi": 144, "xxxhdpi": 192}.items():
    rounded(render(px), 0.2).save(f"{RES}/mipmap-{folder}/ic_launcher.png")

# macOS: rounded body inset 10% with a soft shadow, per Apple's icon grid.
mac_dir = os.path.join(ROOT, "macos/Runner/Assets.xcassets/AppIcon.appiconset")
base = Image.new("RGBA", (1024, 1024), (0, 0, 0, 0))
shadow = Image.new("RGBA", (1024, 1024), (0, 0, 0, 0))
ImageDraw.Draw(shadow).rounded_rectangle([100, 112, 924, 936], 185, fill=(0, 0, 0, 90))
base.alpha_composite(shadow.filter(ImageFilter.GaussianBlur(14)))
base.alpha_composite(rounded(render(824), 185 / 824), (100, 100))
for px in (16, 32, 64, 128, 256, 512, 1024):
    base.resize((px, px), Image.LANCZOS).save(f"{mac_dir}/app_icon_{px}.png")

# Windows .ico.
win_ico = os.path.join(ROOT, "windows/runner/resources/app_icon.ico")
if os.path.isdir(os.path.dirname(win_ico)):
    rounded(render(256), 0.2).save(
        win_ico, sizes=[(s, s) for s in (16, 24, 32, 48, 64, 128, 256)])

# Master artwork for store listings and future use.
icon_dir = os.path.join(ROOT, "assets/icon")
os.makedirs(icon_dir, exist_ok=True)
render(1024).save(f"{icon_dir}/app_icon_1024.png")
# Logo shown in the app's header.
rounded(render(192), 0.22).save(f"{icon_dir}/app_logo.png")
svg_paths = "\n".join(
    f'    <path fill="{c}"' + (' fill-rule="evenodd"' if e else "") + f' d="{p}"/>'
    for c, p, e in foreground)
write(f"{icon_dir}/app_icon.svg", f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72">
  <rect x="18" y="18" width="72" height="72" fill="{BG}"/>
  <g transform="translate({DX} {DY})">
{svg_paths}
  </g>
</svg>
""")
print("icon generated")
